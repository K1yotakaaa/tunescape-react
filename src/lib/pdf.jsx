import React from 'react'
import {
	Document,
	Page,
	Text,
	View,
	StyleSheet,
	Image,
	pdf,
} from '@react-pdf/renderer'

const styles = StyleSheet.create({
	page: {
		backgroundColor: '#0a0a0a',
		color: '#ffffff',
		padding: 40,
		fontFamily: 'Helvetica',
	},
	cover: { backgroundColor: '#0a0a0a' },
	brand: { color: '#1DB954', fontSize: 12, letterSpacing: 4, marginBottom: 8 },
	title: { fontSize: 42, fontWeight: 'bold', marginBottom: 4 },
	subtitle: { color: '#b3b3b3', fontSize: 14, marginBottom: 24 },
	statRow: { flexDirection: 'row', gap: 12, marginTop: 16 },
	statCard: {
		flex: 1,
		backgroundColor: '#121212',
		padding: 14,
		borderRadius: 8,
		borderLeftWidth: 3,
		borderLeftColor: '#1DB954',
	},
	statLabel: { fontSize: 9, color: '#b3b3b3', letterSpacing: 1 },
	statValue: {
		fontSize: 26,
		fontWeight: 'bold',
		color: '#1DB954',
		marginTop: 4,
	},
	sectionTitle: {
		fontSize: 20,
		fontWeight: 'bold',
		marginTop: 24,
		marginBottom: 12,
		borderBottomWidth: 2,
		borderBottomColor: '#1DB954',
		paddingBottom: 6,
	},
	trackRow: {
		flexDirection: 'row',
		alignItems: 'center',
		padding: 8,
		marginBottom: 6,
		backgroundColor: '#121212',
		borderRadius: 6,
	},
	rank: {
		color: '#1DB954',
		fontSize: 16,
		fontWeight: 'bold',
		width: 32,
	},
	coverArt: { width: 42, height: 42, borderRadius: 4, marginRight: 12 },
	trackInfo: { flex: 1 },
	trackName: { fontSize: 12, fontWeight: 'bold' },
	trackArtist: { fontSize: 10, color: '#b3b3b3', marginTop: 2 },
	pop: { color: '#1DB954', fontSize: 11, fontWeight: 'bold' },
	featureRow: { flexDirection: 'row', alignItems: 'center', marginBottom: 8 },
	featureLabel: { width: 110, fontSize: 11, color: '#b3b3b3' },
	featureBarBg: {
		flex: 1,
		height: 8,
		backgroundColor: '#1e1e1e',
		borderRadius: 4,
		marginHorizontal: 8,
	},
	featureBarFill: { height: 8, backgroundColor: '#1DB954', borderRadius: 4 },
	featureValue: {
		width: 40,
		textAlign: 'right',
		fontSize: 11,
		color: '#1DB954',
	},
	footer: {
		position: 'absolute',
		bottom: 20,
		left: 40,
		right: 40,
		fontSize: 9,
		color: '#666',
		textAlign: 'center',
	},
})

function TrackRowPDF({ track, rank }) {
	const img = track.album?.images?.[0]?.url
	return (
		<View style={styles.trackRow}>
			<Text style={styles.rank}>#{rank}</Text>
			{img ? <Image src={img} style={styles.coverArt} /> : null}
			<View style={styles.trackInfo}>
				<Text style={styles.trackName}>{track.name}</Text>
				<Text style={styles.trackArtist}>
					{track.artists?.map(a => a.name).join(', ')}
				</Text>
			</View>
			<Text style={styles.pop}>{track.popularity}</Text>
		</View>
	)
}

function FeatureBar({ label, value }) {
	const pct = Math.min(100, Math.max(0, value * 100))
	return (
		<View style={styles.featureRow}>
			<Text style={styles.featureLabel}>{label}</Text>
			<View style={styles.featureBarBg}>
				<View style={[styles.featureBarFill, { width: `${pct}%` }]} />
			</View>
			<Text style={styles.featureValue}>{Math.round(pct)}%</Text>
		</View>
	)
}

export function ReportDocument({ user, tracks, averages, favorites }) {
	const top10 = tracks.slice(0, 10)
	const uniqueArtists = new Set(
		tracks.flatMap(t => t.artists?.map(a => a.name) || []),
	).size
	const avgPop = tracks.length
		? Math.round(tracks.reduce((s, t) => s + t.popularity, 0) / tracks.length)
		: 0

	return (
		<Document>
			<Page size='A4' style={[styles.page, styles.cover]}>
				<Text style={styles.brand}>TUNESCAPE</Text>
				<Text style={styles.title}>{user?.display_name || 'Your'} Wrapped</Text>
				<Text style={styles.subtitle}>Your music. Anytime.</Text>

				<View style={styles.statRow}>
					<View style={styles.statCard}>
						<Text style={styles.statLabel}>TRACKS</Text>
						<Text style={styles.statValue}>{tracks.length}</Text>
					</View>
					<View style={styles.statCard}>
						<Text style={styles.statLabel}>ARTISTS</Text>
						<Text style={styles.statValue}>{uniqueArtists}</Text>
					</View>
					<View style={styles.statCard}>
						<Text style={styles.statLabel}>AVG POP</Text>
						<Text style={styles.statValue}>{avgPop}</Text>
					</View>
				</View>

				<Text style={styles.sectionTitle}>Top Tracks</Text>
				{top10.map((t, i) => (
					<TrackRowPDF key={t.id} track={t} rank={i + 1} />
				))}

				<Text style={styles.footer}>Generated by Tunescape</Text>
			</Page>

			<Page size='A4' style={styles.page}>
				<Text style={styles.brand}>TUNESCAPE</Text>
				<Text style={styles.title}>Audio DNA</Text>

				{averages ? (
					<View style={{ marginTop: 24 }}>
						<FeatureBar label='Danceability' value={averages.danceability} />
						<FeatureBar label='Energy' value={averages.energy} />
						<FeatureBar label='Valence' value={averages.valence} />
						<FeatureBar label='Acousticness' value={averages.acousticness} />
						<FeatureBar label='Speechiness' value={averages.speechiness} />
						<FeatureBar
							label='Instrumentalness'
							value={averages.instrumentalness}
						/>
					</View>
				) : (
					<Text style={{ color: '#666', marginTop: 24 }}>
						Audio features unavailable.
					</Text>
				)}

				{favorites && favorites.length > 0 && (
					<>
						<Text style={styles.sectionTitle}>Your Favorites</Text>
						{favorites.slice(0, 8).map((f, i) => (
							<View key={f.id} style={styles.trackRow}>
								<Text style={styles.rank}>{i + 1}.</Text>
								<View style={styles.trackInfo}>
									<Text style={styles.trackName}>{f.trackName}</Text>
									<Text style={styles.trackArtist}>
										{f.artistName} · {f.mood} · {'★'.repeat(f.rating)}
									</Text>
								</View>
							</View>
						))}
					</>
				)}

				<Text style={styles.footer}>Generated by Tunescape</Text>
			</Page>
		</Document>
	)
}

export async function downloadReport(data) {
	const blob = await pdf(<ReportDocument {...data} />).toBlob()
	const url = URL.createObjectURL(blob)
	const a = document.createElement('a')
	a.href = url
	a.download = 'tunescape-report.pdf'
	a.click()
	URL.revokeObjectURL(url)
}
